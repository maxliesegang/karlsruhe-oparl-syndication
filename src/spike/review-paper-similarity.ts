/** Hand review of the "ähnlich" index, used to set `PAPER_SIMILARITY_MINIMUM_SCORE`.
 *
 *   npm run review:similarity -- --write   writes a sample to label (never overwrites
 *                                           an existing file without --force)
 *   npm run review:similarity              reports precision per score band from labels
 *   npm run review:similarity -- --context builds original-source context for existing pairs
 *
 * Reads the committed archive only: no network calls, nothing written to docs/. */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import { config } from '../config.js';
import { recordBasename } from '../docs-files.js';
import { SimilarPaper } from '../paper-similarity.js';
import { buildPaperRelationIndex } from '../services/paper-relation-index-service.js';
import {
  findTemplateAbstract,
  stripTemplateBoilerplate,
} from '../services/paper-document-template.js';
import { isMeetingRecordAttachment } from '../services/paper-summary-source.js';
import {
  findSimilarArchivedPapers,
  PAPER_SIMILARITY_MINIMUM_SCORE,
} from '../services/paper-similarity-index-service.js';
import { stores } from '../store/index.js';
import { Paper, PaperSummary } from '../types/index.js';
import {
  buildReviewContext,
  parseSimilarityReview,
  ReviewLabel,
} from './paper-similarity-review.js';

const REVIEW_FILE = 'src/spike/fixtures/similarity-review.md';
const CONTEXT_FILE = 'src/spike/fixtures/similarity-review-context.md';
const SAMPLE_PAPER_COUNT = 30;
/** Reviewed queries are papers a feed reader actually meets. Their neighbours may be
 *  of any age — reaching back in time is the point. */
const SAMPLE_SINCE = '2024-01-01';
const SNIPPET_CHARACTER_LIMIT = 220;
const SCORE_BANDS = [0.5, 0.3, 0.2, 0.15, 0.1, 0.05, 0] as const;

/**
 * `s` same matter (an earlier/later step, a reply, a follow-up),
 * `t` related topic a reader would want pointed out, `n` not useful.
 */
function snippet(paper: Paper): string {
  const basename = recordBasename(paper.id);
  const summaryPath = `docs/summaries/papers/${basename}.json`;
  let text = '';
  if (fs.existsSync(summaryPath)) {
    text = (JSON.parse(fs.readFileSync(summaryPath, 'utf8')) as PaperSummary).summary ?? '';
  }
  if (!text) {
    const attachmentTexts = (paper.auxiliaryFile ?? [])
      .filter((file) => !isMeetingRecordAttachment(file.name))
      .map((file) => stores.fileContents.getById(file.id)?.extractedText)
      .filter((value): value is string => !!value);
    text =
      attachmentTexts.map(findTemplateAbstract).find(Boolean) ??
      (attachmentTexts[0] && stripTemplateBoilerplate(attachmentTexts[0]).slice(0, 600)) ??
      '';
  }
  let flat = text.replace(/\s+/g, ' ').trim();
  // Raw attachment text opens with the letterhead; the title already shows above it.
  const titleAt = paper.name ? flat.indexOf(paper.name) : -1;
  if (titleAt >= 0 && titleAt < 400) flat = flat.slice(titleAt + paper.name.length).trim();
  return flat.length > SNIPPET_CHARACTER_LIMIT
    ? `${flat.slice(0, SNIPPET_CHARACTER_LIMIT)}…`
    : flat || '(kein Text)';
}

function describe(paper: Paper): string {
  return `${paper.reference || '–'} · ${paper.date ?? '–'} · ${paper.paperType}`;
}

/** Deterministic pseudo-random order, so a rerun proposes the same sample. */
function sampleOrder(id: string): string {
  return createHash('sha256').update(id).digest('hex');
}

function writeReview(similar: Map<string, SimilarPaper[]>, papersById: Map<string, Paper>): void {
  if (fs.existsSync(REVIEW_FILE) && !process.argv.includes('--force')) {
    throw new Error(`${REVIEW_FILE} exists; pass --force to replace it and its labels`);
  }

  const queries = [...similar.keys()]
    .filter((id) => (papersById.get(id)?.date ?? '') >= SAMPLE_SINCE)
    .sort((a, b) => sampleOrder(a).localeCompare(sampleOrder(b)))
    .slice(0, SAMPLE_PAPER_COUNT);

  const sections = queries.map((id, index) => {
    const paper = papersById.get(id)!;
    const neighbors = similar.get(id)!.map((neighbor) => {
      const other = papersById.get(neighbor.id)!;
      return (
        `- [ ] \`${neighbor.score.toFixed(3)}\` ${describe(other)} — **${other.name}** <!-- ${id} ${neighbor.id} -->\n` +
        `  > ${snippet(other)}`
      );
    });
    return (
      `### ${index + 1}. ${paper.name}\n\n` +
      `${describe(paper)} · \`papers/${id}.json\`\n\n` +
      `> ${snippet(paper)}\n\n` +
      neighbors.join('\n')
    );
  });

  const header = `# Review: ähnliche Vorlagen

Generated by \`npm run review:similarity -- --write\` from the committed archive.
${queries.length} papers dated ${SAMPLE_SINCE} or later, each with its top 5 TF-IDF
neighbours *before* any score threshold, explicitly related papers already excluded.

Replace the blank in each \`- [ ]\` with one letter:

- \`s\` — same matter: an earlier or later step, a reply, a follow-up
- \`t\` — related topic: a reader of the paper above would want this pointed out
- \`n\` — not useful: same kind of paperwork, a shared word, unrelated
- \`?\` — evidence or usefulness uncertain; excluded from precision, counted as unresolved

Judge as a reader of the paper above would, not by the score. Leave a line blank to
skip it. Run \`npm run review:similarity -- --context\` for longer original-source
excerpts and PDF links without replacing this sample or its labels.
Then run \`npm run review:similarity\` for precision per score band.
Assistant labels must carry \`<!-- reviewer: assistant; confidence: high -->\`
(or medium/low) after the pair comment, with a short reason below. Unannotated
labels are human judgments; remove the assistant annotation when overriding one.
`;
  fs.writeFileSync(REVIEW_FILE, `${header}\n${sections.join('\n\n')}\n`);
  console.log(
    `Wrote ${REVIEW_FILE}: ${queries.length} papers, ` +
      `${queries.reduce((sum, id) => sum + similar.get(id)!.length, 0)} neighbours to label.`,
  );
}

function reportReview(): void {
  if (!fs.existsSync(REVIEW_FILE)) {
    throw new Error(`${REVIEW_FILE} missing; create it with --write`);
  }
  const entries = parseSimilarityReview(fs.readFileSync(REVIEW_FILE, 'utf8'));
  const labelled = entries.filter((entry) => entry.label !== ' ' && entry.label !== '?');
  const blank = entries.filter((entry) => entry.label === ' ').length;
  const uncertain = entries.filter((entry) => entry.label === '?').length;
  if (labelled.length === 0) {
    console.log(`No resolved labels in ${REVIEW_FILE} (${blank} blank, ${uncertain} uncertain).`);
    return;
  }

  const rate = (items: typeof labelled, labels: ReviewLabel[]) =>
    items.length === 0
      ? '   –'
      : `${(
          (100 * items.filter((item) => labels.includes(item.label as ReviewLabel)).length) /
          items.length
        )
          .toFixed(0)
          .padStart(3)}%`;
  const row = (name: string, items: typeof labelled) =>
    `  ${name.padEnd(14)} n=${String(items.length).padStart(3)}  useful (s+t) ${rate(items, ['s', 't'])}  same matter ${rate(items, ['s'])}`;

  console.log(`${labelled.length} resolved, ${blank} blank, ${uncertain} uncertain`);
  console.log(
    '\nBy reviewer (assistant judgments are provisional, not independent human validation):',
  );
  for (const reviewer of ['human', 'assistant'] as const) {
    console.log(
      row(
        reviewer,
        labelled.filter((entry) => entry.reviewer === reviewer),
      ),
    );
  }
  console.log('\nCombined exploratory results — by score band:');
  SCORE_BANDS.forEach((lower, index) => {
    const upper = index === 0 ? Infinity : SCORE_BANDS[index - 1];
    const name = upper === Infinity ? `≥ ${lower}` : `${lower}–${upper}`;
    console.log(
      row(
        name,
        labelled.filter((item) => item.score >= lower && item.score < upper),
      ),
    );
  });
  console.log('\nCumulative — what a threshold would publish:');
  for (const lower of SCORE_BANDS) {
    console.log(
      row(
        `score ≥ ${lower}`,
        labelled.filter((item) => item.score >= lower),
      ),
    );
  }
  console.log('\nBy rank:');
  for (let position = 1; position <= 5; position += 1) {
    console.log(
      row(
        `rank ${position}`,
        labelled.filter((item) => item.rank === position),
      ),
    );
  }
  console.log(`\nCurrent PAPER_SIMILARITY_MINIMUM_SCORE: ${PAPER_SIMILARITY_MINIMUM_SCORE}`);
  const queries = new Set(entries.map((entry) => entry.queryId));
  const retained = entries.filter((entry) => entry.score >= PAPER_SIMILARITY_MINIMUM_SCORE);
  const retainedResolved = retained.filter((entry) => entry.label !== ' ' && entry.label !== '?');
  const withUseful = new Set(
    retained
      .filter((entry) => entry.label === 's' || entry.label === 't')
      .map((entry) => entry.queryId),
  );
  const withAny = new Set(retained.map((entry) => entry.queryId));
  console.log(
    `At this threshold: ${retained.length} recommendations; ${withAny.size}/${queries.size} sampled queries get any, ` +
      `${withUseful.size}/${queries.size} have a judged-useful recommendation; ` +
      `${retained.length - retainedResolved.length} recommendations unresolved.`,
  );
  if (uncertain > 0) {
    console.log('\nUnresolved pairs (find the pair in the source-context companion):');
    for (const entry of entries.filter((item) => item.label === '?')) {
      console.log(`  ${entry.queryId} → ${entry.candidateId}`);
    }
  }
  const mediumCount = labelled.filter(
    (entry) => entry.reviewer === 'assistant' && entry.confidence !== 'high',
  ).length;
  console.log(
    `${mediumCount} resolved assistant judgments have medium/low confidence; spot-check these before treating them as validation.`,
  );
}

if (process.argv.includes('--write') || process.argv.includes('--context')) {
  // An offline review must never schedule PDF downloads, even if .env enables them.
  config.extractPdfText = false;
  await stores.loadFromDisk();
  const papersById = new Map(
    stores.papers.getAll().map((paper) => [recordBasename(paper.id), paper]),
  );
  if (process.argv.includes('--context')) {
    const entries = parseSimilarityReview(fs.readFileSync(REVIEW_FILE, 'utf8'));
    fs.writeFileSync(
      CONTEXT_FILE,
      buildReviewContext(
        entries,
        papersById,
        (file) => stores.fileContents.getById(file.id)?.extractedText,
      ),
    );
    console.log(`Wrote ${CONTEXT_FILE}; existing pairs and labels preserved.`);
  } else {
    // Minimum score 0: the review has to see the band below any candidate threshold.
    writeReview(findSimilarArchivedPapers(buildPaperRelationIndex(), 0), papersById);
  }
} else {
  reportReview();
}
